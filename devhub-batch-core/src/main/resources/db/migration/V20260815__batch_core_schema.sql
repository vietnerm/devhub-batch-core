-- Normalize legacy values: CRON alias -> RECURRING, legacy misfire names kept
-- (FIRE_ONCE / SKIP / RESCHEDULE_NEXT are understood by MisfirePolicy.from).
UPDATE SYS_SCHEDULED_TASKS
SET SCHEDULE_TYPE='RECURRING', SCHEDULED_TIME=NULL
WHERE UPPER(TRIM(COALESCE(SCHEDULE_TYPE,'')))='CRON';

UPDATE SYS_SCHEDULED_TASKS SET REQUEUE_ON_FAILURE = 0 WHERE REQUEUE_ON_FAILURE IS NULL;

