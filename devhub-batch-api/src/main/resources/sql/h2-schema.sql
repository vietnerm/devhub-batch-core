CREATE TABLE IF NOT EXISTS SYS_SCHEDULED_TASKS (
    ID                  BIGINT PRIMARY KEY AUTO_INCREMENT,
    FUNCTION_CODE       VARCHAR(32)  NULL,
    FUNCTION_NAME       VARCHAR(255) NULL,
    TASK_NAME           VARCHAR(100) NOT NULL,
    BEAN_CLASS          VARCHAR(255) NOT NULL,
    SCHEDULE_TYPE       VARCHAR(20)  NOT NULL DEFAULT 'RECURRING',
    CRON_EXPRESSION     VARCHAR(50)  NULL,
    SCHEDULED_TIME      DATETIME     NULL,
    START_AT            DATETIME     NULL,
    END_AT              DATETIME     NULL,
    TIMEZONE            VARCHAR(64)  NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    MISFIRE_POLICY      VARCHAR(24)  NOT NULL DEFAULT 'FIRE_NOW',
    STATUS              VARCHAR(20)  NOT NULL DEFAULT 'SCHEDULED',
    PRIORITY            INT          NOT NULL DEFAULT 0,
    DESCRIPTION         TEXT         NULL,
    REQUEUE_ON_FAILURE  TINYINT      NOT NULL DEFAULT 0,
    TIMEOUT_SECONDS     INT          NOT NULL DEFAULT 3600,
    ATTEMPT_COUNT       INT          NOT NULL DEFAULT 0,
    MAX_ATTEMPT         INT          NOT NULL DEFAULT 3,
    WORKER_ID           VARCHAR(120) NULL,
    CLAIMED_AT          DATETIME     NULL,
    LAST_RUN_AT         DATETIME     NULL,
    NEXT_RUN_AT         DATETIME     NULL,
    CREATED_AT          DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_TASK_NAME UNIQUE (TASK_NAME)
);

CREATE TABLE IF NOT EXISTS SYS_TASK_EXECUTION_LOGS (
    ID                  BIGINT PRIMARY KEY AUTO_INCREMENT,
    TASK_ID             BIGINT       NOT NULL,
    WORKER_ID           VARCHAR(120) NULL,
    STATUS              VARCHAR(20)  NOT NULL,
    RESULT              TEXT         NULL,
    ERROR_MESSAGE       TEXT         NULL,
    EXECUTED_AT         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    STARTED_AT          DATETIME     NULL,
    FINISHED_AT         DATETIME     NULL,
    DURATION_MS         BIGINT       NULL,
    FOREIGN KEY (TASK_ID) REFERENCES SYS_SCHEDULED_TASKS(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SYS_SCHEDULER_WORKERS (
    WORKER_ID           VARCHAR(120) PRIMARY KEY,
    OWNER_ID            VARCHAR(120) NOT NULL DEFAULT 'unknown',
    OWNER_NAME          VARCHAR(255) NOT NULL DEFAULT 'unknown',
    OWNER_EMAIL         VARCHAR(255) NOT NULL DEFAULT 'unknown',
    MACHINE_NAME        VARCHAR(255) NOT NULL DEFAULT 'unknown-host',
    HOSTNAME            VARCHAR(255) NOT NULL DEFAULT 'unknown-host',
    PRIVATE_IP          VARCHAR(64)  NOT NULL DEFAULT 'unknown',
    PUBLIC_IP           VARCHAR(64)  NOT NULL DEFAULT 'unknown',
    MAC_ADDRESS         VARCHAR(32)  NOT NULL DEFAULT 'unknown',
    OS_NAME             VARCHAR(120) NOT NULL DEFAULT 'unknown',
    OS_VERSION          VARCHAR(120) NOT NULL DEFAULT 'unknown',
    OS_ARCH             VARCHAR(64)  NOT NULL DEFAULT 'unknown',
    JAVA_VERSION        VARCHAR(64)  NOT NULL DEFAULT 'unknown',
    JAVA_VENDOR         VARCHAR(255) NOT NULL DEFAULT 'unknown',
    APP_VERSION         VARCHAR(120) NOT NULL DEFAULT 'unknown',
    ENVIRONMENT         VARCHAR(64)  NOT NULL DEFAULT 'default',
    LOCATION            VARCHAR(255) NOT NULL DEFAULT 'unknown',
    CONTAINER_ID        VARCHAR(255) NOT NULL DEFAULT 'unknown',
    PID                 VARCHAR(32)  NULL,
    RUNTIME_ID          VARCHAR(120) NULL,
    STATUS              VARCHAR(20)  NOT NULL DEFAULT 'ONLINE',
    CURRENT_TASK_ID     BIGINT       NULL,
    CURRENT_TASK_NAME   VARCHAR(100) NULL,
    STARTED_AT          DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_HEARTBEAT_AT   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_ERROR          TEXT         NULL,
    UPDATED_AT          DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_STATUS ON SYS_SCHEDULED_TASKS (STATUS);
CREATE INDEX IF NOT EXISTS IDX_NEXT_RUN ON SYS_SCHEDULED_TASKS (NEXT_RUN_AT);
CREATE INDEX IF NOT EXISTS IDX_WORKER_STATUS ON SYS_SCHEDULED_TASKS (WORKER_ID, STATUS);
CREATE INDEX IF NOT EXISTS IDX_REQUEUE_STATUS ON SYS_SCHEDULED_TASKS (REQUEUE_ON_FAILURE, STATUS);
CREATE INDEX IF NOT EXISTS IDX_TASK_TIME ON SYS_TASK_EXECUTION_LOGS (TASK_ID, EXECUTED_AT);
CREATE INDEX IF NOT EXISTS IDX_WORKER_HEARTBEAT ON SYS_SCHEDULER_WORKERS (STATUS, LAST_HEARTBEAT_AT);
